#!/usr/bin/env node
// Pulls WorkAdventure's own wording for meeting invitations (play/src/i18n/<locale>/chat.ts) into Android string
// resources, so the app says what the web client says, in the same 17 languages, and picks up wording changes by
// re-running this script against a newer WorkAdventure tag.
//
//   node android/scripts/gen-wa-strings.mjs [--ref v1.34.0]
//
// Writes android/app/src/main/res/values[-<qualifier>]/wa_strings.xml. A string a locale doesn't define is simply
// left out, and Android falls back to the default (en-US) value. Needs Node 18+ (global fetch) and network.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ref = process.argv.includes("--ref") ? process.argv[process.argv.indexOf("--ref") + 1] : "v1.34.0";
const resDir = join(dirname(fileURLToPath(import.meta.url)), "../app/src/main/res");

// WorkAdventure locale -> Android resource qualifier ("" = the default values/ dir).
const LOCALES = {
  "en-US": "", "ar-SA": "ar", "ca-ES": "ca", "de-DE": "de", "dsb-DE": "b+dsb", "es-ES": "es", "fr-FR": "fr",
  "hsb-DE": "b+hsb", "it-IT": "it", "ja-JP": "ja", "ko-KR": "ko", "nl-NL": "nl", "pt-BR": "pt-rBR", "th-TH": "th",
  "vi-VN": "vi", "zh-CN": "zh-rCN", "zh-TW": "zh-rTW",
};

// Android resource name -> how to find it in chat.ts. `block` limits the search to that object literal.
const KEYS = [
  { name: "wa_accept", key: "accept" },
  { name: "wa_decline", key: "decline" },
  { name: "wa_invite_title", key: "title", block: "meetingInvitation", args: true },
  { name: "wa_invite_declined", key: "invitationDeclined", block: "meetingInvitation", args: true },
  { name: "wa_invite_accepted", key: "invitationAccepted", block: "meetingInvitation", args: true },
  { name: "wa_invite_default_responder", key: "defaultResponderName", block: "meetingInvitation" },
];

const LITERAL = String.raw`("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|` + "`(?:[^`\\\\]|\\\\.)*`" + String.raw`)`;

function unquote(lit) {
  return lit.slice(1, -1).replace(/\\(["'`\\])/g, "$1").replace(/\\n/g, "\n");
}

function find(source, { key, block }) {
  let text = source;
  if (block) {
    const start = source.search(new RegExp(String.raw`\b${block}\s*:\s*\{`));
    if (start < 0) return null;
    const open = source.indexOf("{", start);
    let depth = 0, end = open;
    for (; end < source.length; end++) {
      if (source[end] === "{") depth++;
      else if (source[end] === "}" && --depth === 0) break;
    }
    text = source.slice(open + 1, end);
  }
  const m = text.match(new RegExp(String.raw`(?:^|\n)\s*${key}\s*:\s*${LITERAL}`));
  return m ? unquote(m[1]) : null;
}

// Android string-resource escaping; WorkAdventure's "{name}" becomes the positional format argument %1$s.
function androidString(value, hasArgs) {
  const esc = value
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
  if (!hasArgs) return esc.replace(/%/g, "%%");
  return esc.replace(/%/g, "%%").replace(/\{name\}/g, "%1$s");
}

for (const [locale, qualifier] of Object.entries(LOCALES)) {
  const url = `https://raw.githubusercontent.com/workadventure/workadventure/${ref}/play/src/i18n/${locale}/chat.ts`;
  const res = await fetch(url);
  if (!res.ok) { console.error(`${locale}: HTTP ${res.status}, skipped`); continue; }
  const source = await res.text();
  const lines = [];
  for (const k of KEYS) {
    const v = find(source, k);
    if (v !== null) lines.push(`    <string name="${k.name}">${androidString(v, k.args)}</string>`);
  }
  if (!lines.length) { console.error(`${locale}: none of the keys found, skipped`); continue; }
  const dir = join(resDir, qualifier ? `values-${qualifier}` : "values");
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "wa_strings.xml"),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/scripts/gen-wa-strings.mjs from WorkAdventure ${ref} ` +
      `play/src/i18n/${locale}/chat.ts. Do not edit; re-run the script. -->\n<resources>\n${lines.join("\n")}\n</resources>\n`,
  );
  console.log(`${locale} -> values${qualifier ? "-" + qualifier : ""} (${lines.length} strings)`);
}
